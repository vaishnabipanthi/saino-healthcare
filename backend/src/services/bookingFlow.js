'use strict';

const todayTz = () => new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Kolkata', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date());

async function ensureBookingSchema(db) {
  await db.query(`
    ALTER TABLE provider_appointments
      ADD COLUMN IF NOT EXISTS token_no INTEGER,
      ADD COLUMN IF NOT EXISTS razorpay_order_id TEXT,
      ADD COLUMN IF NOT EXISTS razorpay_payment_id TEXT,
      ADD COLUMN IF NOT EXISTS amount_paid NUMERIC(12,2),
      ADD COLUMN IF NOT EXISTS paid_at TIMESTAMPTZ;
    CREATE INDEX IF NOT EXISTS idx_provider_appointments_queue ON provider_appointments(provider_id, appointment_date, token_no);
    CREATE TABLE IF NOT EXISTS patient_notifications (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      patient_id VARCHAR(50) NOT NULL,
      booking_ref VARCHAR(80),
      type VARCHAR(60) NOT NULL DEFAULT 'booking',
      title TEXT NOT NULL,
      message TEXT NOT NULL,
      payload JSONB NOT NULL DEFAULT '{}'::jsonb,
      is_read BOOLEAN NOT NULL DEFAULT FALSE,
      read_at TIMESTAMPTZ,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    CREATE INDEX IF NOT EXISTS idx_patient_notifications_patient ON patient_notifications(patient_id, created_at DESC);
  `);
}

async function nextToken(db, providerId, date) {
  await db.query('SELECT pg_advisory_xact_lock(hashtext($1::text))', [`token:${providerId}:${date}`]);
  const { rows } = await db.query(`SELECT GREATEST(COALESCE(MAX(token_no), 0), COALESCE(MAX(CASE WHEN token ~ '^Q-[0-9]+$' THEN SUBSTRING(token FROM 3)::integer ELSE 0 END), 0)) + 1 AS n
    FROM provider_appointments WHERE provider_id = $1 AND appointment_date = $2::date`, [providerId, date]);
  const n = Number(rows[0].n);
  return { token_no: n, token: `Q-${String(n).padStart(3, '0')}` };
}

async function notify(db, bookingRef, type, title, message, payload = {}) {
  const result = await db.query(`INSERT INTO patient_notifications(patient_id, booking_ref, type, title, message, payload)
    SELECT patient_id, booking_ref, $2::text, $3::text, $4::text, $5::jsonb
    FROM provider_appointments WHERE booking_ref = $1 AND NULLIF(patient_id, '') IS NOT NULL
    RETURNING id`, [bookingRef, type, title, message, JSON.stringify(payload)]);
  return result.rows[0] || null;
}

async function changeStatus(db, appointment, status, options = {}) {
  const next = String(status).toLowerCase();
  const allowed = new Set(['pending', 'pending_payment', 'confirmed', 'waiting', 'checked_in', 'arrived', 'in_progress', 'completed', 'cancelled', 'no_show']);
  if (!allowed.has(next)) throw new Error('Invalid appointment status');
  const previous = String(appointment.status || '').toLowerCase();
  let token = appointment.token;
  let tokenNo = appointment.token_no;
  if (!token && ['confirmed', 'waiting', 'checked_in', 'arrived', 'in_progress'].includes(next)) {
    const t = await nextToken(db, appointment.provider_id, appointment.appointment_date);
    token = t.token; tokenNo = t.token_no;
  }
  const room = options.room === undefined ? appointment.room : options.room;
  const eta = options.eta === undefined || options.eta === null ? appointment.eta_minutes : options.eta;
  const payment = options.paymentStatus === undefined ? appointment.payment_status : options.paymentStatus;
  const reason = options.reason === undefined ? appointment.reason : options.reason;
  const result = await db.query(`UPDATE provider_appointments SET
    status = $2::varchar, token = $3::varchar, token_no = $4::integer,
    room = $5::varchar, eta_minutes = $6::integer, payment_status = $7::varchar,
    reason = $8::text,
    checked_in_at = CASE WHEN $2::text IN ('checked_in','arrived') AND checked_in_at IS NULL THEN NOW() ELSE checked_in_at END,
    started_at = CASE WHEN $2::text = 'in_progress' AND started_at IS NULL THEN NOW() ELSE started_at END,
    completed_at = CASE WHEN $2::text = 'completed' AND completed_at IS NULL THEN NOW() ELSE completed_at END,
    updated_at = NOW() WHERE id = $1::bigint RETURNING *`,
    [appointment.id, next, token, tokenNo, room, eta, payment, reason]);
  if (!result.rowCount) throw new Error('Appointment no longer exists');
  if (next !== previous) {
    await notify(db, appointment.booking_ref, 'status_update', 'Appointment updated', `Your appointment status is now ${next.replace(/_/g, ' ')}.`, { status: next, token });
  }
  return result.rows[0];
}

module.exports = { todayTz, ensureBookingSchema, nextToken, notify, changeStatus };
