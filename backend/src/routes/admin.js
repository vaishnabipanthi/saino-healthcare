router.post('/providers/:id/status', requireRole('superadmin', 'admin'), async (req, res) => {
  const requested = String((req.body || {}).status || '').trim().toLowerCase();
  const mapping = {
    onboarding_approved: { verification: 'setup_in_progress', status: 'setup_in_progress', published: false, activateUser: true },
    active: { verification: 'verified', status: 'active', published: true },
    verified: { verification: 'verified', status: 'active', published: true },
    approved: { verification: 'verified', status: 'active', published: true },
    rejected: { verification: 'rejected', status: 'rejected', published: false },
    pending_verification: { verification: 'pending', status: 'pending', published: false },
    pending: { verification: 'pending', status: 'pending', published: false },
    suspended: { verification: 'suspended', status: 'suspended', published: false },
    unpublished: { verification: 'verified', status: 'active', published: false }
  };
  const next = mapping[requested];
  if (!next) return res.status(400).json({ success: false, error: 'Choose approve, reject, suspend or unpublish.' });
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const updated = await client.query(`UPDATE providers SET verification_status=$1, status=$2, is_published=$3, updated_at=NOW()
      WHERE id::text=$4 RETURNING *`, [next.verification, next.status, next.published, req.params.id]);
    if (!updated.rowCount) { await client.query('ROLLBACK'); return res.status(404).json({ success: false, error: 'Provider not found.' }); }
    if (next.activateUser) {
      await client.query(`UPDATE users SET is_active=TRUE, updated_at=NOW() WHERE id=(SELECT owner_user_id FROM providers WHERE id=$1)`, [updated.rows[0].id]);
    }
    // Publishing a provider must publish the active doctors and services that its
    // public marketplace page queries. Keep these visibility flags in sync when
    // the listing is approved, unpublished, rejected, or suspended.
    await client.query(`UPDATE doctors SET is_public=$1 WHERE provider_id=$2 AND is_active=TRUE AND status <> 'deleted'`, [next.published, updated.rows[0].id]);
    await client.query(`UPDATE services SET is_public=$1 WHERE provider_id=$2 AND is_active=TRUE AND status <> 'deleted'`, [next.published, updated.rows[0].id]);
    await client.query(`INSERT INTO admin_audit_logs(user_id, action, entity_type, entity_id, details)
      VALUES($1,$2,'provider',$3,$4::jsonb)`, [req.admin.id, `provider_${requested}`, String(req.params.id), JSON.stringify({ verification_status: next.verification, is_published: next.published })]);
    await client.query(`INSERT INTO admin_notifications(title,message,provider_id) VALUES($1,$2,$3)`, [
      'Provider status changed', `${updated.rows[0].name}: ${requested} by Super Admin.`, updated.rows[0].id
    ]);
    await client.query('COMMIT');
    res.json({ success: true, provider: updated.rows[0], public_listing: next.published });
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    console.error('Provider status update failed:', err.message);
    res.status(500).json({ success: false, error: 'Provider status could not be saved.' });
  } finally { client.release(); }
});

