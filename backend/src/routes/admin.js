let adminSchemaReady = false;
let adminSchemaPromise = null;

function getJwtSecret() {
  const secret = process.env.JWT_SECRET;
  if (!secret || secret.length < 32) throw new Error('Set JWT_SECRET to a random value with at least 32 characters in backend/.env.');
  return secret;
}
function asInt(v) { return Number.parseInt(v || '0', 10) || 0; }
function publicId(prefix) { return `${prefix}-${crypto.randomBytes(5).toString('hex').toUpperCase()}`; }

async function ensureAdminTables() {
  if (adminSchemaReady) return;
  if (adminSchemaPromise) return adminSchemaPromise;
  adminSchemaPromise = (async () => {
    await ensureProviderTables();
    await pool.query(`
      CREATE TABLE IF NOT EXISTS admin_audit_logs (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
        action VARCHAR(160) NOT NULL,
        entity_type VARCHAR(100) NOT NULL,
        entity_id TEXT,
        details JSONB NOT NULL DEFAULT '{}'::jsonb,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      ALTER TABLE admin_audit_logs ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES users(id) ON DELETE SET NULL;
      ALTER TABLE users ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMPTZ;
      ALTER TABLE users ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();
      CREATE INDEX IF NOT EXISTS idx_admin_audit_created_at ON admin_audit_logs(created_at DESC);
      CREATE INDEX IF NOT EXISTS idx_admin_audit_entity ON admin_audit_logs(entity_type, entity_id);
    `);
    adminSchemaReady = true;
  })();
  try { await adminSchemaPromise; }
  catch (err) { adminSchemaPromise = null; throw err; }
}

async function writeAudit(req, action, entityType, entityId, details = {}) {
  await pool.query(`INSERT INTO admin_audit_logs(user_id, action, entity_type, entity_id, details)
    VALUES($1,$2,$3,$4,$5::jsonb)`, [req.admin?.id || null, action, entityType, entityId == null ? null : String(entityId), JSON.stringify(details)]);
}
function requireRole(...roles) {
  return (req, res, next) => {
    if (!req.admin) return res.status(401).json({ success: false, code: 'ADMIN_AUTH_REQUIRED', error: 'Please sign in to Super Admin.' });
    if (!roles.includes(String(req.admin.role || '').toLowerCase())) return res.status(403).json({ success: false, error: 'Your account does not have permission for this action.' });
    next();
  };
}

// First-time Super Admin sign-in: account must be created locally with `npm run create:superadmin`.
router.post('/login', async (req, res) => {
  try {
    await ensureAdminTables();
    const email = String((req.body || {}).email || '').trim().toLowerCase();
    const password = String((req.body || {}).password || '');
    if (!email || !password) return res.status(400).json({ success: false, error: 'Enter the Super Admin email and password.' });
    const found = await pool.query(`SELECT id, full_name, email, password_hash, role, is_active
      FROM users WHERE LOWER(email) = $1 AND LOWER(role) IN ('superadmin','admin','operations','finance','support') LIMIT 1`, [email]);
    const user = found.rows[0];
    if (!user || user.is_active !== true || !user.password_hash || !(await bcrypt.compare(password, user.password_hash))) {
      return res.status(401).json({ success: false, error: 'Email or password is incorrect, or the admin account is inactive.' });
    }
    const token = jwt.sign({ userId: String(user.id), role: String(user.role).toLowerCase() }, getJwtSecret(), { expiresIn: '8h', issuer: 'saino-health-admin' });
    await pool.query('UPDATE users SET last_login_at = NOW(), updated_at = NOW() WHERE id = $1', [user.id]);
    await writeAudit({ admin: user }, 'admin_login', 'user', user.id, { role: user.role });
    res.json({ success: true, token, user: { id: user.id, name: user.full_name, email: user.email, role: user.role } });
  } catch (err) {
    console.error('Admin login failed:', err.message);
    res.status(503).json({ success: false, error: 'Super Admin login is unavailable. Verify the backend/database configuration.' });
  }
});

