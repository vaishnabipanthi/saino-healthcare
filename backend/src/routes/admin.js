// Every platform-management API below this point requires a verified database-backed admin JWT.
router.use(async (req, res, next) => {
  try {
    await ensureAdminTables();
    const match = String(req.headers.authorization || '').match(/^Bearer\s+(.+)$/i);
    if (!match) return res.status(401).json({ success: false, code: 'ADMIN_AUTH_REQUIRED', error: 'Please sign in to Super Admin.' });
    const claims = jwt.verify(match[1], getJwtSecret(), { issuer: 'saino-health-admin' });
    const found = await pool.query(`SELECT id, full_name, email, role, is_active FROM users
      WHERE id = $1 AND LOWER(role) IN ('superadmin','admin','operations','finance','support') LIMIT 1`, [claims.userId]);
    const user = found.rows[0];
    if (!user || user.is_active !== true || String(user.role).toLowerCase() !== String(claims.role).toLowerCase()) {
      return res.status(401).json({ success: false, code: 'ADMIN_AUTH_REQUIRED', error: 'Admin account is inactive or session expired.' });
    }
    req.admin = user;
    next();
  } catch (err) {
    if (err.name === 'JsonWebTokenError' || err.name === 'TokenExpiredError') {
      return res.status(401).json({ success: false, code: 'ADMIN_AUTH_REQUIRED', error: 'Admin session expired. Please sign in again.' });
    }
    console.error('Admin authorization failed:', err.message);
    return res.status(503).json({ success: false, error: 'Could not validate the admin session.' });
  }
});

